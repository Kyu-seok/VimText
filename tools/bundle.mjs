// Dependency-free bundler for the content script.
//
// Why this exists: MV3 content scripts can't use static ES `import`, and a
// runtime `import(chrome.runtime.getURL(...))` is blocked by strict page CSPs
// (Chrome 130+). So we keep the sources as ES modules (unit-tested in Node) and
// concatenate them here into ONE classic IIFE — content-scripts/vimtext.js —
// that's listed directly in the manifest. No runtime import → no CSP surface.
//
// The transform is intentionally simple and only works because the sources obey
// two conventions (enforced by review + the bundle staying in sync in CI):
//   1. every top-level name is unique across all modules, and
//   2. exports are inline declarations (`export function/const/…`), never
//      `export { ... }` or `export default`.
// Run: node tools/bundle.mjs  (or `npm run build`)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const csDir = path.join(__dirname, "..", "content-scripts");

// Concatenation order = dependency order (a module's deps come before it).
const FILES = [
  "engine/state.js",
  "engine/motions.js",
  "engine/operators.js",
  "engine/textobjects.js",
  "engine/surround.js",
  "engine/keymap.js",
  "dom/write.js",
  "dom/element-tracker.js",
  "dom/cursor.js",
  "dom/mode-indicator.js",
  "dom/search-ui.js",
  "index.js",
];

const ENDS_IMPORT = /from\s+["'][^"']+["'];?\s*$/;

// Drop `import` statements (single- and multi-line) and the `export` keyword
// from inline declarations. Import detection is anchored to lines beginning with
// `import`, so the words "import"/"export" inside comments or strings are safe.
// Aliased imports (`X as Y`) become `const Y = X;` so the alias survives — every
// module is concatenated in dependency order, so `X` is already defined.
function strip(src) {
  const out = [];
  const lines = src.split("\n");
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*import\b/.test(lines[i])) {
      let stmt = lines[i];
      while (
        !ENDS_IMPORT.test(stmt) &&
        !/^\s*import\s+["'][^"']+["'];?\s*$/.test(stmt) &&
        i + 1 < lines.length
      ) {
        stmt += "\n" + lines[++i];
      }
      const braces = stmt.match(/\{([\s\S]*?)\}/);
      if (braces) {
        for (const spec of braces[1].split(",")) {
          const m = spec.trim().match(/^(\w+)\s+as\s+(\w+)$/);
          if (m) out.push(`const ${m[2]} = ${m[1]};`);
        }
      }
      continue;
    }
    out.push(lines[i].replace(/^(\s*)export\s+(function|const|let|var|class|async)\b/, "$1$2"));
  }
  return out.join("\n").trim();
}

const parts = [
  "// AUTO-GENERATED by tools/bundle.mjs — do not edit by hand.",
  "// Source of truth: content-scripts/{engine,dom}/*.js + index.js (ES modules).",
  "// Regenerate with `npm run build`. Bundled to a classic script so strict page",
  "// CSPs can't block a runtime dynamic import().",
  "(function () {",
  '"use strict";',
];

for (const f of FILES) {
  parts.push(`\n// ==== ${f} ====`);
  parts.push(strip(fs.readFileSync(path.join(csDir, f), "utf8")));
}

parts.push("\ninit();");
parts.push("})();");

const output = parts.join("\n") + "\n";

// Guard: every module shares one scope in the bundle, so duplicate top-level
// names silently clobber each other (legal JS — last declaration wins). Catch
// it at build time. Module-level declarations sit at column 0 after stripping;
// nested ones are indented, so a start-anchored match finds only top-level names.
const seen = new Set();
const dups = new Set();
for (const line of output.split("\n")) {
  const m = line.match(/^(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/);
  if (!m) continue;
  if (seen.has(m[1])) dups.add(m[1]);
  else seen.add(m[1]);
}
if (dups.size) {
  throw new Error(
    `Duplicate top-level name(s) in bundle: ${[...dups].join(", ")}\n` +
    `Rename so every module's top-level declarations are unique.`
  );
}

const outPath = path.join(csDir, "vimtext.js");
fs.writeFileSync(outPath, output);
console.log(`wrote content-scripts/vimtext.js (${fs.statSync(outPath).size} bytes)`);
